pattern = r"(const (\w+) = useCallback\(\(\.\.\.args: any\[\]\) => )\.apply\(null, args\)"

def replace_line(m):
    prefix, name = m.group(1), m.group(2)
    store = store_map.get(name)
    if store:
        return f'{prefix}{store}.{name}.apply(null, args)'
    return m.group(0)

content = re.sub(pattern, replace_line, content)

